'use strict';

/**
 * Builds the bundled starter playlist from data/channels.json.
 *
 * The JSON manifest is the single source of truth so the channel list, the
 * rights matrix in docs/CHANNELS.md, and the stream verification script can
 * never drift apart.
 */

const fs = require('node:fs');
const path = require('node:path');

const projectRoot = path.join(__dirname, '..');
const manifestPath = path.join(projectRoot, 'data', 'channels.json');
const m3uPath = path.join(projectRoot, 'app', 'data', 'public-channels.m3u');
const jsPath = path.join(projectRoot, 'app', 'default-playlist.js');

function quote(value) {
  return '"' + String(value === undefined || value === null ? '' : value).replace(/"/g, "'").replace(/[\r\n]+/g, ' ') + '"';
}

function toM3u(channels) {
  const lines = ['#EXTM3U'];
  channels.forEach(function (channel) {
    const attributes = [
      ['tvg-id', channel.tvgId],
      ['tvg-name', channel.name],
      ['tvg-chno', channel.number],
      ['group-title', channel.category],
      ['tvg-language', channel.language],
      ['tvg-country', channel.country],
      ['tvg-logo', channel.logo],
      ['source-page', channel.sourcePage],
      ['backup-url', channel.backupUrl],
      ['verified-at', channel.verifiedAt],
      ['rights-note', channel.rights],
      ['hls-note', channel.hlsNotes]
    ]
      .filter(function (pair) { return pair[1]; })
      .map(function (pair) { return pair[0] + '=' + quote(pair[1]); })
      .join(' ');
    lines.push('#EXTINF:-1 ' + attributes + ',' + channel.name);
    lines.push(channel.url);
  });
  return lines.join('\n') + '\n';
}

function toStarterScript(channels) {
  const payload = {
    version: 2,
    updatedAt: channels.updatedAt || '2026-10-29',
    channels: channels
  };
  return [
    '/* Generated by scripts/build-lineup.js from data/channels.json. Do not edit by hand. */',
    '(function (root) {',
    "  'use strict';",
    '  root.FREEWAVE_STARTER = ' + JSON.stringify(payload, null, 2).replace(/\n/g, '\n  ') + ';',
    '})(window);',
    ''
  ].join('\n');
}

function main() {
  const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
  const channels = (manifest.channels || []).filter(function (channel) {
    return channel && channel.status === 'verified';
  });
  channels.updatedAt = manifest.updatedAt;
  if (!channels.length) throw new Error('No verified channels in data/channels.json');
  fs.mkdirSync(path.dirname(m3uPath), { recursive: true });
  fs.writeFileSync(m3uPath, toM3u(channels), 'utf8');
  fs.writeFileSync(jsPath, toStarterScript(channels), 'utf8');
  console.log('Wrote ' + channels.length + ' channels to app/data/public-channels.m3u and app/default-playlist.js');
}

if (require.main === module) main();

module.exports = { toM3u: toM3u, toStarterScript: toStarterScript };
